using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Godot;
using OpenWC3.UI;

namespace OpenWC3.Game;

internal static class FdfBindGen
{
    internal readonly record struct Target(string ClassName, string RootFrame, string[] Sources);

    internal static readonly Target[] Targets =
    {
        new("ConsoleUiBinding", "ConsoleUI", new[]
        {
            @"UI\FrameDef\GlobalStrings.fdf",
            @"UI\FrameDef\UI\ConsoleUI.fdf",
        }),
        new("ResourceBarBinding", "ResourceBarFrame", new[]
        {
            @"UI\FrameDef\GlobalStrings.fdf",
            @"UI\FrameDef\UI\ResourceBar.fdf",
        }),
        new("UpperButtonBarBinding", "UpperButtonBarFrame", new[]
        {
            @"UI\FrameDef\GlobalStrings.fdf",
            @"UI\FrameDef\UI\UpperButtonBar.fdf",
        }),
        new("LoadingScreenBinding", "Loading", new[]
        {
            @"UI\FrameDef\GlobalStrings.fdf",
            @"UI\FrameDef\Glue\StandardTemplates.fdf",
            @"UI\FrameDef\Glue\Loading.fdf",
        }),
        new("MainMenuBinding", "MainMenuFrame", new[]
        {
            @"UI\FrameDef\GlobalStrings.fdf",
            @"UI\FrameDef\Glue\StandardTemplates.fdf",
            @"UI\FrameDef\Glue\MainMenu.fdf",
        }),
        new("EscMenuMainPanelBinding", "EscMenuMainPanel", new[]
        {
            @"UI\FrameDef\GlobalStrings.fdf",
            @"UI\FrameDef\UI\EscMenuTemplates.fdf",
            @"UI\FrameDef\UI\EscMenuMainPanel.fdf",
        }),
    };

    public static int Run(string outputDirectory)
    {
        if (string.IsNullOrWhiteSpace(outputDirectory))
        {
            outputDirectory = Path.Combine(ProjectSettings.GlobalizePath("res://"),
                "GameCore", "L4_Composition", "Game", "UI", "Generated");
        }
        Directory.CreateDirectory(outputDirectory);

        int failures = 0;
        foreach (Target target in Targets)
        {
            var factory = new FdfUiFactory(NullTextureResolver.Instance, ReadFdf);
            foreach (string fdf in target.Sources) factory.Parse(fdf);
            UiFrame root = factory.Create(target.RootFrame);
            if (root == null)
            {
                Console.Error.WriteLine($"  [bindgen] FAIL {target.ClassName}: 根帧 {target.RootFrame} 未找到");
                failures++;
                continue;
            }
            string path = Path.Combine(outputDirectory, target.ClassName + ".g.cs");
            File.WriteAllText(path, Emit(target, root), new UTF8Encoding(false));
            Console.WriteLine($"  [bindgen] {path}（{CountFrames(root)} 帧）");
        }
        Console.WriteLine(failures == 0
            ? $"FDF bindgen：{Targets.Length} 个绑定已生成"
            : $"FDF bindgen：{failures}/{Targets.Length} 个失败");
        return failures == 0 ? 0 : 1;
    }

    private static string ReadFdf(string path)
    {
        if (string.IsNullOrWhiteSpace(path)) return null;
        string key = path.Replace('\\', '/').TrimStart('/');
        return Generated.FdfTables.All.TryGetValue(key, out string text) ? text : null;
    }

    private static int CountFrames(UiFrame frame) => 1 + frame.Children.Sum(CountFrames);

    private static void Collect(UiFrame frame, string parentField,
        List<(string Field, string Type, string Name, string Parent)> into, HashSet<string> seen)
    {
        string field = null;
        if (!string.IsNullOrEmpty(frame.Name) && IsIdentifier(frame.Name) && seen.Add(frame.Name))
        {
            field = frame.Name;
            into.Add((field, frame.GetType().Name, frame.Name, parentField));
        }
        foreach (UiFrame child in frame.Children) Collect(child, field ?? parentField, into, seen);
    }

    private static bool IsIdentifier(string name) =>
        name.Length > 0 && (char.IsLetter(name[0]) || name[0] == '_')
        && name.All(c => char.IsLetterOrDigit(c) || c == '_');

    private static string Emit(Target target, UiFrame root)
    {
        var frames = new List<(string Field, string Type, string Name, string Parent)>();
        Collect(root, null, frames, new HashSet<string>(StringComparer.Ordinal));
        string rootField = frames[0].Field;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> 由 Launcher --fdf-bindgen 生成, 请勿手改。");
        sb.AppendLine($"// 来源 FDF: {string.Join(", ", target.Sources)}");
        sb.AppendLine("using System;");
        sb.AppendLine("using OpenWC3.UI;");
        sb.AppendLine();
        sb.AppendLine("namespace OpenWC3.Game.UI.Generated;");
        sb.AppendLine();
        sb.AppendLine($"internal sealed class {target.ClassName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string RootFrameName = \"{target.RootFrame}\";");
        sb.AppendLine();
        sb.AppendLine("    public static readonly string[] Sources =");
        sb.AppendLine("    {");
        foreach (string s in target.Sources) sb.AppendLine($"        @\"{s}\",");
        sb.AppendLine("    };");
        sb.AppendLine();
        foreach (var (field, type, _, _) in frames)
            sb.AppendLine($"    public {type} {field};");
        sb.AppendLine();
        sb.AppendLine("    public static " + target.ClassName + " Load(FdfUiFactory factory, UiFrame parent = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        foreach (string source in Sources) factory.Parse(source);");
        sb.AppendLine("        UiFrame root = factory.Create(RootFrameName, parent);");
        sb.AppendLine("        if (root == null) return null;");
        sb.AppendLine($"        var binding = new {target.ClassName}();");
        sb.AppendLine("        return binding.Bind(root) ? binding : null;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public bool Bind(UiFrame root)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (root == null) return false;");
        sb.AppendLine($"        {rootField} = root as {frames[0].Type} ?? throw new InvalidCastException(");
        sb.AppendLine($"            $\"{target.RootFrame} 期望 {frames[0].Type}, 实际 {{root.GetType().Name}}\");");
        sb.AppendLine("        bool ok = true;");
        foreach (var (field, type, name, parent) in frames.Skip(1))
        {
            string from = parent ?? rootField;
            sb.AppendLine($"        {field} = {from}?.FindByName<{type}>(\"{name}\");");
            sb.AppendLine($"        if ({field} == null) {{ Missing(\"{name}\"); ok = false; }}");
        }
        sb.AppendLine("        return ok;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    static void Missing(string name) =>");
        sb.AppendLine($"        Console.WriteLine($\"  [fdf] {target.ClassName}: 缺少帧 {{name}}\");");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private sealed class NullTextureResolver : IUiTextureResolver
    {
        public static readonly NullTextureResolver Instance = new();
        public RHI.ITexture Resolve(string path) => null;
    }
}
